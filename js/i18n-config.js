// Initialize i18next
function initI18n() {
  const savedLang = localStorage.getItem('civitasSolisLang') || 'pt';
  
  i18next.init({
    lng: savedLang,
    fallbackLng: 'pt',
    resources: {
      pt: { translation: translations.pt },
      en: { translation: translations.en }
    }
  });
}

// Translation helper function
function t(key) {
  return i18next.t(key);
}

// Change language function
function changeLanguage(lang) {
  i18next.changeLanguage(lang);
  localStorage.setItem('civitasSolisLang', lang);
  document.documentElement.lang = lang;
  
  // Trigger a custom event to notify components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Get current language
function getCurrentLanguage() {
  return i18next.language || 'pt';
}

// Initialize on load
if (typeof window !== 'undefined') {
  window.addEventListener('DOMContentLoaded', initI18n);
}
